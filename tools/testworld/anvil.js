// Minimal Anvil region-file reader/writer (.mca) for the test-world tools.
// Chunk payloads are kept as parsed prismarine-nbt trees so callers can edit them.

const fs = require('fs')
const path = require('path')
const zlib = require('zlib')
const nbt = require('prismarine-nbt')

const SECTOR = 4096

function regionFile (dir, cx, cz) {
  return path.join(dir, `r.${cx >> 5}.${cz >> 5}.mca`)
}

// Returns the parsed NBT tree of chunk (cx, cz) in a region dir, or null if absent.
async function readChunk (dir, cx, cz) {
  const file = regionFile(dir, cx, cz)
  if (!fs.existsSync(file)) return null
  const buf = fs.readFileSync(file)
  const i = 4 * ((cx & 31) + (cz & 31) * 32)
  const sectorOff = buf.readUIntBE(i, 3)
  if (sectorOff === 0) return null
  const off = sectorOff * SECTOR
  const len = buf.readUInt32BE(off)
  const comp = buf[off + 4]
  if (comp & 128) throw new Error(`chunk ${cx},${cz} is stored externally (.mcc), unsupported`)
  const data = buf.subarray(off + 5, off + 4 + len)
  let raw
  if (comp === 1) raw = zlib.gunzipSync(data)
  else if (comp === 2) raw = zlib.inflateSync(data)
  else if (comp === 3) raw = data
  else throw new Error(`chunk ${cx},${cz}: unsupported compression ${comp}`)
  return (await nbt.parse(raw)).parsed
}

// Writes region files for a list of { cx, cz, tree } into dir (replacing any existing files
// those chunks fall in; chunks not listed are simply absent and get generated by the server).
function writeChunks (dir, chunks) {
  fs.mkdirSync(dir, { recursive: true })
  const byRegion = new Map()
  for (const c of chunks) {
    const f = regionFile(dir, c.cx, c.cz)
    if (!byRegion.has(f)) byRegion.set(f, [])
    byRegion.get(f).push(c)
  }
  const now = Math.floor(Date.now() / 1000)
  for (const [file, list] of byRegion) {
    const header = Buffer.alloc(2 * SECTOR)
    const bodies = []
    let sector = 2
    for (const c of list) {
      const data = zlib.deflateSync(nbt.writeUncompressed(c.tree, 'big'))
      const n = Math.ceil((data.length + 5) / SECTOR)
      const body = Buffer.alloc(n * SECTOR)
      body.writeUInt32BE(data.length + 1, 0)
      body[4] = 2
      data.copy(body, 5)
      const i = 4 * ((c.cx & 31) + (c.cz & 31) * 32)
      header.writeUIntBE(sector, i, 3)
      header[i + 3] = n
      header.writeUInt32BE(now, SECTOR + i)
      bodies.push(body)
      sector += n
    }
    fs.writeFileSync(file, Buffer.concat([header, ...bodies]))
  }
}

module.exports = { readChunk, writeChunks }
